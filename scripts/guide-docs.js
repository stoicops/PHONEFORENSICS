// Renders the in-app phone-data guides as Markdown, so docs/SAVING-PHONE-DATA.md never drifts.
// Usage: node scripts/guide-docs.js > docs/SAVING-PHONE-DATA.md

import { GUIDES } from "../src/phoneforensics/static/js/content.js";

/** @param {string | { value: string }} text */
const toMarkdown = (text) =>
  String(typeof text === "string" ? text : text.value)
    .replace(/<a [^>]*href="([^"]+)"[^>]*>([^<]+)<\/a>/g, "[$2]($1)")
    .replace(/<\/?b>/g, "**")
    .replace(/<span class="pf-mono">([^<]+)<\/span>/g, "`$1`")
    .replace(/<code>([^<]+)<\/code>/g, "`$1`")
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&");

export function renderGuides() {
  let out = "# Saving data from a phone\n\n";
  out +=
    "<!-- Generated by scripts/guide-docs.js from src/phoneforensics/static/js/content.js. Do not edit by hand. -->\n\n";
  out += "These are the same step-by-step guides shown in the PhoneForensics app (Guide tab).\n\n";
  for (const guide of Object.values(GUIDES)) {
    out += `## ${guide.title}\n\n${toMarkdown(guide.intro)}\n\n`;
    out += guide.steps.map(([title, text], i) => `${i + 1}. **${toMarkdown(title)}** ${toMarkdown(text)}`).join("\n");
    out += "\n\n**If something goes wrong**\n\n";
    out += guide.trouble.map(([question, answer]) => `- **${toMarkdown(question)}** ${toMarkdown(answer)}`).join("\n");
    out += "\n\n";
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(renderGuides());
